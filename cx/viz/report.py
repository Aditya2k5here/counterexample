"""Build ``results/report.html`` and ``results/summary.md`` from the experiment.

The report re-runs each shrunk counterexample -- which costs nothing, because a
choice sequence is an exact reproduction -- captures the trace, and draws it.
"""

import json
import os

from ..eval.run import RESULTS_DIR
from ..raft.node import BUGS
from ..sim.scenario import run
from . import spacetime


def build_report(results_path=None, out_path=None):
    results_path = results_path or os.path.join(RESULTS_DIR, "results.json")
    out_path = out_path or os.path.join(RESULTS_DIR, "report.html")
    with open(results_path) as fh:
        results = json.load(fh)

    cases = []
    for bug, entry in sorted(results.get("shrunk", {}).items()):
        r = run(values=entry["choices"], bugs=[bug], pad_zero=True, keep_trace=True)
        if not r.violations:
            continue
        v = r.violations[0]
        servers = ["s%d" % i for i in range(r.n_servers)]
        clients = sorted({rec["client"] for rec in r.trace.records
                          if rec["kind"] in ("invoke", "ok")})
        svg = spacetime.render_svg(r.trace, servers, clients, violation=v)
        story = spacetime.story(r.trace, v, servers)
        stats = entry["stats"]
        meta = ("%d nodes  ·  shrunk from %d to %d decisions (%.0f%% smaller) in "
                "%.0fs over %d candidate runs  ·  failure at t=%dms"
                % (r.n_servers, stats["from"], stats["to"],
                   100 * stats["reduction"], stats["seconds"], stats["attempts"],
                   v.time))
        cases.append({
            "bug": bug,
            "description": BUGS[bug],
            "violation": "%s -- %s" % (v.prop, v.detail),
            "svg": svg,
            "story": story,
            "choices": entry["choices"],
            "meta": meta,
        })

    spacetime.build_page(cases, out_path)
    return out_path, len(cases)


def build_summary(results_path=None, out_path=None):
    results_path = results_path or os.path.join(RESULTS_DIR, "results.json")
    out_path = out_path or os.path.join(RESULTS_DIR, "summary.md")
    with open(results_path) as fh:
        r = json.load(fh)

    methods = r["config"]["methods"]
    lines = ["<!-- generated by `python -m cx report`; do not edit -->", ""]

    if r.get("validation"):
        lines += ["## Validation: the correct implementation survives the search", ""]
        total = sum(v["schedules"] for v in r["validation"].values())
        fp = sum(v["false_positives"] for v in r["validation"].values())
        lines += ["| search | schedules | false positives |", "|---|---|---|"]
        for m in methods:
            v = r["validation"][m]
            lines.append("| `%s` | %s | **%d** |"
                         % (m, "{:,}".format(v["schedules"]), v["false_positives"]))
        lines += ["", "%s adversarial schedules against the unmodified implementation, "
                  "%d reported violations. Any number other than zero here would make "
                  "everything below meaningless." % ("{:,}".format(total), fp), ""]

    lines += ["## Bug benchmark: trials until the first violation", "",
              "Budget %d trials, %d independent seeds per cell. `x/%d` is how many "
              "seeds found the bug; the number after it is the median trial count "
              "over the seeds that did."
              % (r["config"]["bug_budget"], r["config"]["bug_seeds"],
                 r["config"]["bug_seeds"]), ""]
    lines += ["| seeded defect | " + " | ".join("`%s`" % m for m in methods)
              + " | first symptom |", "|" + "---|" * (len(methods) + 2)]
    for bug, entry in r["benchmark"].items():
        cells = []
        sig = None
        for m in methods:
            d = entry["methods"][m]
            if d["found"]:
                cells.append("%d/%d, med %g" % (d["found"], d["of"], d["median_trials"]))
                sig = sig or (sorted(d["signatures"]) or [None])[0]
            else:
                cells.append("—")
        lines.append("| `%s` | %s | %s |" % (bug, " | ".join(cells), sig or "not found"))
    lines.append("")

    if r.get("deep"):
        lines += ["## The rare defects, at a budget where \"not found\" means something", "",
                  "Three defects need a specific interleaving that a random schedule "
                  "reaches almost never. Running them at the same budget as the easy "
                  "ones and calling that a comparison would be an underpowered "
                  "experiment dressed up as a result, so they get 1,000 trials each.", ""]
        lines += ["| defect | seeds | " + " | ".join("`%s`" % m for m in methods) + " |",
                  "|" + "---|" * (len(methods) + 2)]
        for bug, cells in sorted(r["deep"].items()):
            seeds = max(c["of"] for c in cells.values())
            row = []
            for m in methods:
                c = cells.get(m)
                if not c:
                    row.append("—")
                elif c["found"]:
                    row.append("%d/%d, med %g" % (c["found"], c["of"], c["median_trials"]))
                else:
                    row.append("0/%d" % c["of"])
            lines.append("| `%s` | %d | %s |" % (bug, seeds, " | ".join(row)))
        lines.append("")

    if r.get("shrunk"):
        lines += ["## Shrinking", "",
                  "Every failure arrives as a choice sequence of thousands of "
                  "integers. Delta debugging cuts it down to a run whose remaining "
                  "decisions are the ones that mattered.", "",
                  "| seeded defect | property | decisions before | after | reduction |",
                  "|---|---|---|---|---|"]
        for bug, s in sorted(r["shrunk"].items()):
            st = s["stats"]
            lines.append("| `%s` | %s | %s | **%d** | %.0f%% |"
                         % (bug, s["signature"], "{:,}".format(st["from"]),
                            st["to"], 100 * st["reduction"]))
        lines.append("")

    lines += ["## The seeded defects", "",
              "| name | what was broken |", "|---|---|"]
    for bug in r["benchmark"]:
        lines.append("| `%s` | %s |" % (bug, BUGS[bug]))
    lines.append("")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return out_path


def main():
    s = build_summary()
    print("wrote", s)
    p, n = build_report()
    print("wrote %s (%d counterexamples, %.2f MB)"
          % (p, n, os.path.getsize(p) / 1e6))


if __name__ == "__main__":
    main()
